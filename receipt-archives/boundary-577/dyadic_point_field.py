"""Replay the 577-class certificate and the two places in its affine point field.

Run with Python 3.11 or later. The large prime certificate was generated by
PARI/GP. Verification here uses only integer arithmetic and the Hasse bound.
"""

import json
from math import comb, gcd, isqrt
from pathlib import Path


P = 577
TRACE = 3_319_228_075_515
HOST_PRIME = 2011
DISCRIMINANT_PRIME = 2 ** (P + 2) - TRACE**2


def small_prime(n):
    return n >= 2 and all(n % d for d in range(2, isqrt(n) + 1))


def add_points(left, right, a, modulus):
    """A finite result is affine over every prime factor of the modulus."""
    if left is None:
        return right
    if right is None:
        return left
    x, y = left
    u, v = right
    if x == u:
        if (y + v) % modulus == 0:
            return None
        assert y == v
        slope = (3 * x * x + a) * pow(2 * y, -1, modulus) % modulus
    else:
        slope = (v - y) * pow(u - x, -1, modulus) % modulus
    nx = (slope * slope - x - u) % modulus
    return nx, (slope * (x - nx) - y) % modulus


def multiply(k, point, a, modulus):
    out = None
    while k:
        if k & 1:
            out = add_points(out, point, a, modulus)
        k //= 2
        if k:
            point = add_points(point, point, a, modulus)
    return out


def prove_prime():
    terminal = 25_460_792_818_498_519
    factors = [2, 3, 13, 181787, 1795620263]
    n_minus_one = 1
    for v in factors:
        assert small_prime(v)
        n_minus_one *= v
    assert n_minus_one == terminal - 1 and pow(3, terminal - 1, terminal) == 1
    assert all(
        gcd(pow(3, (terminal - 1) // q, terminal) - 1, terminal) == 1 for q in factors
    )
    # For each prime divisor of terminal the reduction of 3 has full order.
    path = Path(__file__).with_name("dyadic_prime_certificate.json")
    rows = json.loads(path.read_text(encoding="ascii"))
    assert len(rows) == 18
    known_prime = terminal
    for n, trace, cofactor, curve_a, (x, y) in reversed(rows):
        assert n > 3 and gcd(n, 6) == 1 and cofactor > 0
        assert cofactor * known_prime == n + 1 - trace
        assert known_prime > (isqrt(isqrt(n)) + 2) ** 2
        curve_b = (y * y - x**3 - curve_a * x) % n
        assert gcd(4 * curve_a**3 + 27 * curve_b**2, n) == 1
        q_torsion = multiply(cofactor, (x % n, y % n), curve_a, n)
        assert q_torsion is not None
        assert multiply(known_prime, q_torsion, curve_a, n) is None
        # A prime divisor <= sqrt(n) could not have a point of this order.
        known_prime = n
    assert known_prime == DISCRIMINANT_PRIME
    return len(rows)


def dickson(n, x, b, modulus):
    prev, cur = 2, x % modulus
    for _ in range(1, n):
        prev, cur = cur, (x * cur - b * prev) % modulus
    return prev if n == 0 else cur


def roots_of_point_polynomial():
    d = DISCRIMINANT_PRIME
    assert small_prime(P) and small_prime(HOST_PRIME)
    assert d % 16 == 7 and HOST_PRIME % 8 == 3 and (d + 1) % HOST_PRIME == 0
    assert 2 * 576 + 1 < HOST_PRIME < d
    assert d > 4 * 2 ** (P - 1)
    assert TRACE % (P * P) == (1 + pow(2, P, P * P)) % (P * P) == 188682
    assert (-d) % P == 1
    assert dickson(P, 3, 2, P * P) == TRACE % (P * P)
    modulus = P**3
    root = (1 - (1 - TRACE + 2**P) * pow(2 - TRACE, -1, modulus)) % modulus
    assert (root * root - TRACE * root + 2**P) % modulus == 0 and root == 1 + 499 * P**2
    anti = root * pow(TRACE - root, -1, modulus) % modulus
    assert pow(anti, P - 1, modulus) == 1 + 281 * P**2
    # Detection independent of the lower bound on the dyadic ideal order.
    r = 20773
    assert small_prime(r) and r - 1 == 36 * P
    assert 3106**2 % r == (-d) % r
    alpha = (TRACE + 3106) * pow(2, -1, r) % r
    assert alpha == 1285 and pow(alpha, 36, r) == 11328
    assert all(pow(2, (r - 1) // q, r) != 1 for q in (2, 3, P))
    assert pow(pow(2, 36, r), 226, r) == 11328 != 1
    # Test the Dickson recurrence independently on the two-parameter formula.
    for m in (P * P, r):
        for unit in (1, 2, 3, 5, 7, 11):
            other = 2 * pow(unit, -1, m) % m
            assert (
                dickson(P, unit + other, 2, m)
                == (pow(unit, P, m) + pow(other, P, m)) % m
            )


def short_host_witness():
    d = DISCRIMINANT_PRIME
    r = 6911
    assert small_prime(r) and r % 256 == 255
    assert 103**2 - 2 * 43**2 == r and 103 > 43 * 2
    assert pow(r, (HOST_PRIME - 1) // 2, HOST_PRIME) == 1
    assert pow(r, (d - 1) // 2, d) == 1
    t = pow(2, (d + 1) // 4, d)
    assert t * t % d == 2
    assert all(
        pow((103 + sign * 43 * t) % d, (d - 1) // 2, d) == d - 1 for sign in (-1, 1)
    )


def check_corner_constant():
    # At the reduced weight the summands in one complete block give B_k,eta
    # by Faulhaber. Check it separately using the Bernoulli recurrence.
    k = P - 2
    eta = (0, 1, 1, -1, 1, -1, -1)
    moment = sum(eta[a % 7] * pow(a, k, P * P) for a in range(1, 7 * P + 1)) % (P * P)
    assert moment == 30004 and (moment // P) * pow(7, -1, P) % P == 502
    bernoulli = [1]
    for n in range(1, k + 1):
        total, choose = 0, 1
        for j, value in enumerate(bernoulli):
            total += choose * value
            choose = choose * (n + 1 - j) // (j + 1)
        bernoulli.append(-total * pow(n + 1, -1, P) % P)
    bg = (
        sum(
            comb(k, j)
            * bernoulli[j]
            * pow(7, j - 1, P)
            * sum(v * pow(a, k - j, P) for a, v in enumerate(eta))
            for j in range(k + 1)
        )
        % P
    )
    assert bg == 502 and -bg * pow(2 * k, -1, P) % P == 414


def main():
    steps = prove_prime()
    roots_of_point_polynomial()
    short_host_witness()
    check_corner_constant()
    print(
        f"{steps} elliptic certificates prove primality of the {DISCRIMINANT_PRIME.bit_length()}-bit d."
    )
    print(
        "Dyadic ideal order 577; local Kummer roots 1 and 2 at 577; Frobenius exponent 226 at 20773."
    )
    print(
        "Point field: polynomial index 577, local degrees 1 and 576. The full host norm fails at 6911."
    )


if __name__ == "__main__":
    main()
